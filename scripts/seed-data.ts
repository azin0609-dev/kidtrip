interface Existing {
  id: string;
  lat: number | null;
  lng: number | null;
  google_place_id: string | null;
}
function loadExisting(file: string): Map<string, Existing> {
  const path = `${root}data/${file}`;
  if (!existsSync(path)) return new Map();
  try {
    return new Map((JSON.parse(readFileSync(path, 'utf8')) as Existing[]).map((x) => [x.id, x]));
  } catch {
    return new Map();
  }
}

const oldSpots = loadExisting('spots.json');
const spots = SPOTS.map(([name, city, region, types, env, cost_tier, stroller, mins, tip, extra], i) => {
  const id = `spot-${String(i + 1).padStart(3, '0')}`;
  const old = oldSpots.get(id);
  const verify = new Set<string>(['mins_from_linkou', ...(extra?.verify ?? [])]);
  if (cost_tier === '?') verify.add('cost_tier');
  return {
    id,
    name,
    city,
    region,
    types,
    env,
    cost_tier,
    stroller_ok: stroller === 1,
    mins_from_linkou: mins,
    tip,
    ...(extra?.badge ? { badge: extra.badge } : {}),
    ...(extra?.opens_on ? { opens_on: extra.opens_on } : {}),
    ...(extra?.closes_on ? { closes_on: extra.closes_on } : {}),
    lat: old?.lat ?? null,
    lng: old?.lng ?? null,
    google_place_id: old?.google_place_id ?? null,
    needs_verify: [...verify],
    last_verified: TODAY,
  };
});

const idByName = new Map(spots.map((s) => [s.name, s.id]));
const oldHotels = loadExisting('hotels.json');
const hotels = HOTELS.map(([name, city, region, price_tier, tags, features, mins, tip, near, verify], i) => {
  const id = `hotel-${String(i + 1).padStart(3, '0')}`;
  const old = oldHotels.get(id);
  return {
    id,
    name,
    city,
    region,
    price_tier,
    tags,
    features,
    mins_from_linkou: mins,
    tip,
    near_spot_ids: near.map((n) => {
      const sid = idByName.get(n);
      if (!sid) throw new Error(`${name}：找不到景點「${n}」`);
      return sid;
    }),
    lat: old?.lat ?? null,
    lng: old?.lng ?? null,
    google_place_id: old?.google_place_id ?? null,
    needs_verify: ['mins_from_linkou', 'price_tier', 'tags', ...(verify ?? [])],
    last_verified: TODAY,
  };
});

writeFileSync(`${root}data/spots.json`, JSON.stringify(spots, null, 2) + '\n');
writeFileSync(`${root}data/hotels.json`, JSON.stringify(hotels, null, 2) + '\n');
